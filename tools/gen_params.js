// Generates core/FxParams.h from the web app's params.js (the single source of the parameter table)
const fs=require('fs');const path=process.argv[2]||'/home/claude/fx-web/params.js';
const pj=fs.readFileSync(path,'utf8');const {D,IDX,DST,DSTP,FXN}=new Function(pj+';return {D,IDX,DST,DSTP,FXN}')();
const q0=IDX['q0f0model'],q1=IDX['q1f0model'],stride=q1-q0;
// every slot block must be laid out identically and contiguously
for(let q=0;q<8;q++)for(let j=0;j<stride;j++){const d=D[q0+q*stride+j];const ref=D[q0+j];if(d.id!=='q'+q+ref.id.slice(2))throw new Error('slot layout '+q+' '+j)}
const esc=s=>JSON.stringify(s);const f=x=>(Number.isInteger(x)?x.toFixed(1):String(x))+'f';
let o='// Generated by tools/gen_params.js from the web params.js. Do not edit.\n#pragma once\nnamespace fxp {\n';
o+=`constexpr int NP=${D.length};\nconstexpr int SLOT_BASE=${q0};\nconstexpr int SLOT_STRIDE=${stride};\nconstexpr int NDST=${DST.length};\n`;
o+='struct PDef{const char* id;const char* name;char type;float mn,mx,df;int nch;const char* choices;};\n';
o+='static const PDef PDEFS[NP]={\n'+D.map(d=>` {${esc(d.id)},${esc(d.nm)},'${d.t}',${f(d.mn)},${f(d.mx)},${f(d.df)},${d.ch?d.ch.length:0},${esc(d.ch&&d.ch.length<=64?d.ch.join('|'):'')}}`).join(',\n')+'};\n';
o+='static const int DSTP[NDST]={'+DSTP.join(',')+'};\n';
// global parameter indices
const glob=D.map((d,i)=>[d.id,i]).filter(([id])=>!/^q\d/.test(id));
o+='namespace G{enum:int{\n'+glob.map(([id,i])=>` ${id.replace(/[^A-Za-z0-9_]/g,'_')}=${i}`).join(',\n')+'};}\n';
// slot-local indices (offset from a slot's base)
o+='namespace L{enum:int{\n'+D.slice(q0,q0+stride).map((d,j)=>` ${d.id.slice(2)}=${j}`).join(',\n')+'};}\n';
o+='}\n';
fs.writeFileSync('core/FxParams.h',o);console.log('params',D.length,'stride',stride,'globals',glob.length,'dst',DST.length);
